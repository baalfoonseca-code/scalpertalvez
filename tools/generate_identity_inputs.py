#!/usr/bin/env python3
"""Generate actual input serialization and honest build provenance; no preset values.

Run after source edits, before the final verification/commit. Build digest excludes
BookBuildIdentity.mqh itself to avoid a circular hash. Revision is explicitly the
revision *at generation*, never a claim that uncommitted source equals that commit.
"""
from pathlib import Path
import argparse
import hashlib
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
INPUT = re.compile(r'^\s*input\s+(\w+)\s+(\w+)\s*=\s*([^;]+);', re.M)
BOOK91_REFERENCE = '815077efec40adf1897bcf64640756bb46c4c118'
RESEARCH103_REFERENCE = '94fddd73f0455c63a6cd238d6cb9f8924e9a497a'


def expand(path, seen=None):
    seen = set() if seen is None else seen
    if path in seen:
        return ''
    seen.add(path)
    content = path.read_text(encoding='utf-8')
    def include(match):
        candidate = path.parent / match[1].replace('\\', '/')
        return expand(candidate.resolve(), seen) if candidate.exists() else ''
    return re.sub(r'^\s*#include\s+"([^"]+)"\s*$', include, content, flags=re.M)


def snapshot(source):
    inputs = INPUT.findall(expand(source))
    if len({name for _, name, _ in inputs}) != len(inputs):
        raise ValueError('duplicate input declaration')
    original = INPUT.findall((ROOT / 'scalpertalvez').read_text(encoding='utf-8'))
    if len(original) != 71 or inputs[:71] != original:
        raise ValueError('historic inputs changed in name/type/order/default')
    book91 = INPUT.findall(subprocess.check_output(
        ['git', 'show', f'{BOOK91_REFERENCE}:scalpertalvez_MONOLITICO.mq5'],
        cwd=ROOT, text=True))
    if len(book91) != 91 or inputs[:91] != book91:
        raise ValueError('audited BOOK 91 inputs changed in name/type/order/default')
    research103 = INPUT.findall(subprocess.check_output(
        ['git', 'show', f'{RESEARCH103_REFERENCE}:REMORA_BOOK_PRO_DECISORIA.mq5'],
        cwd=ROOT, text=True))
    if len(research103) != 103 or inputs[:103] != research103:
        raise ValueError('audited decision 103 inputs changed in name/type/order/default')
    if inputs[103:] != [('bool', 'Inp_ResearchEnable', 'false')]:
        raise ValueError('only input bool Inp_ResearchEnable=false may be appended')
    lines = ['// Generated by tools/generate_identity_inputs.py; actual loaded values.',
             '#ifndef BOOK_INPUT_SNAPSHOT_MQH', '#define BOOK_INPUT_SNAPSHOT_MQH',
             'void BookCollectInputIdentity(string &canonical)', '{']
    for kind, name, _ in inputs:
        if kind == 'string':
            value = name
        elif kind == 'bool':
            value = f'({name}?"1":"0")'
        elif kind in ('double', 'float'):
            value = f'StringFormat("%.17g",{name})'
        elif kind == 'datetime':
            value = f'(string)(long){name}'
        else:
            value = f'(string)(int){name}'
        lines.append(f'   BookIdentityAdd(canonical,"{kind}","{name}",{value});')
    lines.extend(['}', '#endif', ''])
    return '\n'.join(lines), inputs


def bundle_digest():
    digest = hashlib.sha256()
    paths = [ROOT / 'scalpertalvez.mq5', *sorted((ROOT / 'Include').glob('*.mqh'))]
    for path in paths:
        if path.name == 'BookBuildIdentity.mqh':
            continue
        name = path.relative_to(ROOT).as_posix().encode()
        data = path.read_bytes()
        digest.update(str(len(name)).encode() + b':' + name)
        digest.update(str(len(data)).encode() + b':' + data)
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, inputs = snapshot(ROOT / 'scalpertalvez.mq5')
    path = ROOT / 'Include/BookInputSnapshot.mqh'
    if args.check:
        if path.read_text() != generated:
            raise SystemExit('input snapshot stale; regenerate')
        source_hash = bundle_digest()
        saved = (ROOT / 'Include/BookBuildIdentity.mqh').read_text()
        if f'"{source_hash}"' not in saved:
            raise SystemExit('source build digest stale; regenerate')
        print(f'identity verified: {len(inputs)} inputs, historic 71 intact, source_sha256={source_hash}')
        return
    path.write_text(generated, encoding='utf-8')
    sha = bundle_digest()
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    build = '\n'.join(['// Generated provenance, not a native compilation certificate.',
        '#ifndef BOOK_BUILD_IDENTITY_MQH', '#define BOOK_BUILD_IDENTITY_MQH',
        '#define BOOK_BASELINE_REVISION "a31f7b03701dd13b5c26801669552001d3ed634c"',
        f'#define BOOK_REVISION_AT_GENERATION "{revision}"',
        '#define BOOK_BUILD_ID "BOOK1125_DECISION_RESEARCH_EXP1"',
        f'#define BOOK_SOURCE_BUNDLE_SHA256 "{sha}"', '#endif', ''])
    (ROOT / 'Include/BookBuildIdentity.mqh').write_text(build, encoding='utf-8')
    print(f'generated {len(inputs)} loaded-input bindings, source_sha256={sha}')


if __name__ == '__main__':
    main()
