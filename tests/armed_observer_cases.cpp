// Included after the current MQL5 observer, with only host API/type adaptation.
int main() {
 int cases=0;
 BookDiagInit("preset-A");
 assert(gBookDiagReady && gBookDiagCount==1); ++cases;
 MatrixSnapshot matrix{}; matrix.status=MSS_OK; matrix.c1=true;
 armed.route="ABS"; armed.mode="BASE"; armed.dir=1;
 armed.regionHigh=100; armed.regionLow=90; armed.regionEndTime=900;
 armed.armedAt=clock_sec; armed.breakoutEffortMin=1.5;
 BookDiagSelected(matrix,armed,105);
 string first_id=gBookDiagState.id;
 assert(gBookDiagState.active && first_id!="" && gBookDiagCount==2); ++cases;
 BookDiagBeginEvaluation(); BookDiagWait(BD_BREAKOUT,"WAIT_BREAKOUT");
 assert(gBookDiagCount==2); ++cases; // No queue work inside original gate evaluation.
 BookDiagAfterEvaluation();
 assert(gBookDiagCount==3); ++cases;
 BookDiagAfterEvaluation();
 assert(gBookDiagCount==3 && gBookDiagDeduplicated==1); ++cases;
 clock_sec++;
 MqlTick tick{}; tick.last=105; tick.bid=104; tick.ask=105; tick.time_msc=clock_sec*1000;
 BookDiagBeginEvaluation(); BookDiagTick(tick,105); BookDiagPass(BD_BREAKOUT);
 BookDiagLive(1.0,100,100,1); BookDiagWait(BD_WAVE_EFFORT,"WAIT_LIVE_WAVE_EFFORT");
 BookDiagAfterEvaluation();
 assert(gBookDiagState.trace.touched && gBookDiagState.last_reason=="WAIT_LIVE_WAVE_EFFORT"); ++cases;
 BookDiagBeginEvaluation();
 BookGateDecision decision{};
 BookDiagBookReadBegin(); BookDiagBook(decision,false);
 assert(!gBookDiagState.book_consulted && gBookDiagState.trace.blocked==BD_DATA); ++cases;
 assert(gBookDiagState.last_reason=="WAIT_DATA:BOOK_NOT_CONSULTED"); ++cases;
 BookDiagBeginEvaluation(); BookDiagBookReadBegin(); BookDiagBookAttempt();
 decision.pctBid=40; decision.pctAsk=60; BookDiagBook(decision,false);
 assert(gBookDiagState.book_consulted && gBookDiagState.trace.blocked==BD_BOOK); ++cases;
 BookDiagAudit("TIMEOUT_ARMED");
 assert(!gBookDiagState.active && gBookDiagState.terminal=="TIMEOUT_TRIGGER_REACHED_BUT_BLOCKED"); ++cases;
 auto count=gBookDiagCount; BookDiagBeforeReset(); assert(count==gBookDiagCount); ++cases;
 clock_sec++;
 BookDiagSelected(matrix,armed,105); assert(gBookDiagState.id!=first_id); ++cases;
 MqlTradeResult result{}; result.request_id=10; result.order=20; result.retcode=10009;
 BookDiagDispatch(result);
 assert(!gBookDiagState.active && gBookDiagAwaiting[0].used); ++cases;
 assert(gBookDiagState.terminal=="ORDER_SENT_AWAITING_SERVER_PROOF"); ++cases;
 TradeRecord record{}; record.entryOrderTicket=20; record.positionID=30;
 record.totalVolumeIn=1; record.weightedEntryPrice=105; record.direction=1;
 record.route="ABS"; record.mode="BASE";
 count=gBookDiagCount; BookDiagConfirmed(record);
 assert(gBookDiagCount==count && gBookDiagAwaiting[0].used); ++cases;
 record.accountingResolved=true; record.entryOrderTicket=99; BookDiagConfirmed(record);
 assert(gBookDiagCount==count && gBookDiagAwaiting[0].used); ++cases;
 record.entryOrderTicket=20; BookDiagConfirmed(record);
 assert(gBookDiagCount==count+1 && !gBookDiagAwaiting[0].used); ++cases;
 assert(gBookDiagQueue[(gBookDiagHead+gBookDiagCount-1)%BOOK_DIAG_QUEUE_CAP].event=="ORDER_CONFIRMED"); ++cases;
 clock_sec++; BookDiagSelected(matrix,armed,105);
 result.request_id=11; result.order=0; result.deal=0; result.retcode=10006;
 BookDiagDispatch(result); assert(!gBookDiagAwaiting[0].used); ++cases;
 bool failed=false;
 for(int i=0;i<gBookDiagCount;i++) if(gBookDiagQueue[i].event=="ORDER_FAILED") failed=true;
 assert(failed); ++cases;
 clock_sec++; BookDiagSelected(matrix,armed,105);
 gBookDiagCount=BOOK_DIAG_QUEUE_CAP;
 BookDiagEmit("TERMINAL","FORCE_CAPACITY",true);
 assert(gBookDiagSuspended && gBookDiagSuspension=="QUEUE_CAPACITY" && gBookDiagDropped==1); ++cases;
 std::cout<<"armed_observer_cases: "<<cases<<" deterministic host-adapted collection cases passed\n";
}
